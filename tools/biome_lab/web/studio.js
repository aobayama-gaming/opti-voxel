// Biome studio: one biome's landscape in 3D, then how it blends with its neighbours. The 3D is a climate report run of
// a table derived from the edited one (view_table: the biome alone, its region's biomes, or the table as it is), the
// heights the engine computes. The full editor (editor.html) covers every other key of the table.
import * as THREE from "three";
import { $, el, api, toast, go_to, take_handoff, handed_off } from "./common.js";
import { View3D, flat_weight } from "./view3d.js";

const QUICK_SIZE = 128; // points per side after an edit: ~6 s on world.json; SHARP_SIZE ~25 s
const SHARP_SIZE = 256;
const EDIT_DELAY_MS = 600;
const UNDO_MAX = 200;
const EXTENTS_KM = [1, 2, 4, 8, 16, 32, 64, 128, 256];
const MODES = {
    solo: ["Alone", "This biome everywhere, on its region's relief: its own landscape."],
    landform: ["With its neighbours", "The biomes of its region, the region everywhere: how they blend."],
    world: ["Whole world", "The table as the game reads it."],
};
const SHAPES = ["", "plain", "billow", "ridged", "square"];
// The ground's colours without a surface (Material::GROUND_FLAT / GROUND_STEEP, linear).
const GROUND_FLAT = new THREE.Color().setRGB(0.24, 0.36, 0.16, THREE.LinearSRGBColorSpace);
const GROUND_STEEP = new THREE.Color().setRGB(0.36, 0.32, 0.28, THREE.LinearSRGBColorSpace);

const S = {
    path: null, data: null, saved: "", tables: [], undo: [], redo: [], gesture: false,
    biome: null, mode: "solo", relief: {}, extent: { solo: 8, landform: 32, world: 128 }, center: [0, 0],
    exaggeration: 1, colors: "surface", water: false, voxel: "0.05", lods: "25",
    timer: null, token: 0, run: null, probe: null, framed: "",
};
let view = null;

// --- prefs ---

function store_prefs() {
    const keep = ({ path, biome, mode, relief, extent, center, exaggeration, colors, water, voxel, lods }) =>
        ({ path, biome, mode, relief, extent, center, exaggeration, colors, water, voxel, lods });
    try { localStorage.setItem("biome_studio", JSON.stringify(keep(S))); } catch { /* private window */ }
}

function load_prefs() {
    try { Object.assign(S, JSON.parse(localStorage.getItem("biome_studio") || "{}")); } catch { /* none */ }
}

// --- the table being edited ---

const biomes = () => S.data?.biomes || [];
const current = () => biomes().find((b) => b.name === S.biome);
const dirty = () => S.data !== null && JSON.stringify(S.data) !== S.saved;

function set_table(p_path, p_data, p_saved) {
    S.path = p_path;
    S.data = p_data;
    S.saved = p_saved;
    S.undo = [];
    S.redo = [];
    if (!current()) S.biome = biomes().at(-1)?.name ?? null;
    $("#table").value = p_path;
    render_all();
    run(QUICK_SIZE);
}

async function open_table(p_path) {
    if (dirty() && !confirm(`Discard the unsaved changes to ${S.path}?`)) { $("#table").value = S.path; return; }
    const r = await api(`/api/table?path=${encodeURIComponent(p_path)}`);
    set_table(r.path, r.data, JSON.stringify(r.data));
    store_prefs();
}

// An edit: one undo step per gesture (a slider drag is one), the view recomputed shortly after.
function edit(p_fn, p_end = true) {
    if (!S.gesture) {
        S.undo.push(JSON.stringify(S.data));
        if (S.undo.length > UNDO_MAX) S.undo.shift();
        S.redo = [];
        S.gesture = true;
    }
    p_fn();
    if (p_end) end_gesture();
    render_header();
    clearTimeout(S.timer);
    S.timer = setTimeout(() => run(QUICK_SIZE), EDIT_DELAY_MS);
}

// A gesture that changed nothing leaves no undo step.
function end_gesture() {
    S.gesture = false;
    if (S.undo.at(-1) === JSON.stringify(S.data)) S.undo.pop();
    render_header();
}

function undo(p_from, p_to) {
    if (!p_from.length) return;
    p_to.push(JSON.stringify(S.data));
    S.data = JSON.parse(p_from.pop());
    S.gesture = false;
    if (!current()) S.biome = biomes().at(-1)?.name ?? null;
    render_all();
    run(QUICK_SIZE);
}

async function save() {
    const t = S.tables.find((x) => x.path === S.path);
    if (t?.generated && !confirm(`${S.path} is generated by tools/landforms/world.py from the landform tables: running it again overwrites these edits. Save anyway?`)) return;
    try {
        const r = await api("/api/save", { path: S.path, data: S.data });
        S.saved = JSON.stringify(S.data);
        render_header();
        toast(r.unchanged ? `${r.saved}: unchanged` : `saved ${r.saved}`);
    } catch (e) { toast(e.message, true); }
}

// --- the table the view shows ---

// The region whose heights a biome stands on when shown alone: its own region, else the region of its name (a
// table's default biome, like world.json's mountain, often has one), else none (the heights without a region).
function relief_of(p_b) {
    if (p_b.name in S.relief) return S.relief[p_b.name];
    return p_b.region ?? (S.data.regions || []).find((r) => r.name === p_b.name)?.name ?? "";
}

function region_key(p_b) { return p_b.region ?? relief_of(p_b); }

// The heights of one region (and those of none), made global.
function heights_on(p_region) {
    return (S.data.heights || []).filter((h) => !h.region || h.region === p_region).map((h) => {
        const c = structuredClone(h);
        delete c.region;
        return c;
    });
}

function without_region(p_b) {
    const c = structuredClone(p_b);
    delete c.region;
    return c;
}

// The biomes of the selected one's region (the biomes without one share theirs).
function neighbours() {
    const b = current();
    return biomes().filter((x) => (x.region ?? "") === (b.region ?? ""));
}

function view_table() {
    const b = current();
    if (S.mode === "world" || !b) return S.data;
    const rest = { ...S.data };
    delete rest.regions;
    if (S.mode === "solo") {
        const one = without_region(b);
        delete one.where;
        return { ...rest, heights: heights_on(relief_of(b)), biomes: [one] };
    }
    const group = neighbours().map(without_region);
    delete group.at(-1).where; // the region's default: the last biome takes no edges
    return { ...rest, heights: heights_on(region_key(b)), biomes: group };
}

// --- running the report ---

async function bin(p_run, p_name, p_type) {
    const r = await fetch(`/api/run?run=${encodeURIComponent(p_run)}&name=${p_name}`);
    if (!r.ok) throw new Error(`${p_name}: ${r.statusText}`);
    return new p_type(await r.arrayBuffer());
}

// A report of the view's table; a newer run makes this one moot (the server stops it, its result is dropped).
async function run(p_size) {
    clearTimeout(S.timer);
    if (!S.data || !current()) return;
    const token = ++S.token;
    const frame = [S.path, S.biome, S.mode, S.extent[S.mode], S.center.join(",")].join("|");
    const params = { voxel: S.voxel, lods: S.lods, extent_km: String(S.extent[S.mode]), size: String(p_size), center: S.center.join(",") };
    status(`computing ${p_size} × ${p_size}…`, true);
    view.stale(true);
    try {
        let j = await api("/api/check", { path: S.path, data: view_table(), params });
        while (j.state === "queued" || j.state === "running") {
            await new Promise((r) => setTimeout(r, 300));
            if (token !== S.token) return;
            j = await api(`/api/job?id=${j.id}`);
        }
        if (token !== S.token) return;
        const r = j.result;
        $("#refused").hidden = !!r?.ok;
        if (!r?.ok) {
            $("#refused").textContent = r?.error || j.output.slice(-2000) || `exit ${j.code}`;
            status(r?.refused ? "refused by the engine" : "the report failed");
            return;
        }
        const [h, picks] = await Promise.all([bin(r.run, "heights.f32", Float32Array), bin(r.run, "picks.u8", Uint8Array)]);
        if (token !== S.token) return;
        S.run = { meta: r.heights, h, picks, size: p_size };
        S.probe = null;
        $("#probe").hidden = true;
        paint(frame !== S.framed);
        S.framed = frame;
    } catch (e) {
        if (token === S.token) { status(e.message); toast(e.message, true); }
    }
}

// The run's mesh in the biomes' colours as they are now (a colour edit repaints without a run).
function paint(p_frame = false) {
    const R = S.run;
    if (!R) return;
    const byname = new Map(biomes().map((b) => [b.name, b]));
    const looks = R.meta.biomes.map((name) => {
        const b = byname.get(name);
        if (S.colors === "debug") {
            const c = new THREE.Color(b?.debug_color || "#888888");
            return { flat: c, steep: c };
        }
        const s = b?.surface;
        return s ? { flat: new THREE.Color(s.flat || "#888888"), steep: new THREE.Color(s.steep || s.flat || "#888888") } : { flat: GROUND_FLAT, steep: GROUND_STEEP };
    });
    const mixed = new THREE.Color();
    const stats = view.set(R.h, R.meta.n, R.meta.spacing_m, (i, up) => {
        const l = looks[R.picks[i]] || looks[0];
        return mixed.copy(l.steep).lerp(l.flat, flat_weight(up));
    }, p_frame);
    const m = (v) => `${Math.round(v)} m`;
    status(`${MODES[S.mode][0]} · ${S.extent[S.mode]} km · ${R.meta.spacing_m.toFixed(1)} m between points · ground ${m(stats.lo)} to ${m(stats.hi)}`
        + (R.size < SHARP_SIZE ? " · quick" : ""));
}

function status(p_text, p_busy = false) {
    const s = $("#status");
    s.textContent = p_text;
    s.classList.toggle("busy", p_busy);
}

// --- rendering ---

function render_all() {
    render_header();
    render_biomes();
    render_modes();
    render_viewbar();
    render_controls();
}

function render_header() {
    const d = dirty();
    const b = $("#dirty");
    b.textContent = d ? "unsaved" : "saved";
    b.className = d ? "badge warn" : "badge";
    $("#undo").disabled = !S.undo.length;
    $("#redo").disabled = !S.redo.length;
}

function chip(p_color) { return el("span", { class: "chip", style: `background:${p_color || "transparent"}` }); }

function render_biomes() {
    const nav = $("#biomes");
    nav.innerHTML = "";
    let group = null;
    for (const b of biomes()) {
        const g = b.region ?? "";
        if (g !== group) {
            group = g;
            nav.append(el("div", { class: "group" }, g || "no region"));
        }
        nav.append(el("button", { class: "item" + (b.name === S.biome ? " sel" : ""), title: b.where ? "" : "the default: where no other biome of its region grows",
            onclick: () => { S.biome = b.name; store_prefs(); render_all(); run(QUICK_SIZE); } },
            chip(b.debug_color), el("span", { class: "name" }, b.name), b.where ? null : el("span", { class: "tag" }, "default")));
    }
}

function render_modes() {
    const box = $("#modes");
    box.innerHTML = "";
    for (const [k, [label]] of Object.entries(MODES)) {
        box.append(el("button", { class: S.mode === k ? "on" : "", onclick: () => { S.mode = k; store_prefs(); render_all(); run(QUICK_SIZE); } }, label));
    }
    box.append(el("span", { class: "help" }, MODES[S.mode][1]));
}

function render_viewbar() {
    const bar = $("#viewbar");
    bar.innerHTML = "";
    const extent = el("select", { title: "The slice's side" }, EXTENTS_KM.map((k) => el("option", { value: k, selected: k === S.extent[S.mode] }, `${k} km`)));
    extent.addEventListener("change", () => { S.extent[S.mode] = Number(extent.value); store_prefs(); run(QUICK_SIZE); });
    const center = el("input", { type: "text", value: S.center.join(","), title: "The slice's centre, U,V metres (double-click the ground to move there)" });
    center.addEventListener("change", () => {
        const p = center.value.split(",").map(Number);
        if (p.length !== 2 || p.some((v) => !Number.isFinite(v))) { toast("the centre is U,V in metres", true); return; }
        S.center = p.map(Math.round);
        store_prefs();
        run(QUICK_SIZE);
    });
    const exag = el("input", { type: "range", min: 1, max: 5, step: 0.25, value: S.exaggeration, title: "Vertical exaggeration" });
    exag.addEventListener("input", () => { S.exaggeration = Number(exag.value); view.set_exaggeration(S.exaggeration); store_prefs(); });
    const colors = el("select", {}, el("option", { value: "surface", selected: S.colors === "surface" }, "ground colours"),
        el("option", { value: "debug", selected: S.colors === "debug" }, "biome colours"));
    colors.addEventListener("change", () => { S.colors = colors.value; store_prefs(); paint(); });
    const water = el("input", { type: "checkbox", checked: S.water });
    water.addEventListener("change", () => { S.water = water.checked; view.show_water(S.water); store_prefs(); });
    const setting = (k, label, title) => {
        const i = el("input", { type: "text", value: S[k], title, style: "width:52px" });
        i.addEventListener("change", () => { S[k] = i.value.trim(); store_prefs(); run(QUICK_SIZE); });
        return el("label", {}, label, i);
    };
    bar.append(el("label", {}, "size", extent), el("label", {}, "centre", center),
        el("button", { onclick: () => { S.center = [0, 0]; store_prefs(); render_viewbar(); run(QUICK_SIZE); } }, "Back to 0,0"),
        el("button", { class: "primary", title: `${SHARP_SIZE} × ${SHARP_SIZE} points, ~25 s`, onclick: () => run(SHARP_SIZE) }, "Sharpen"),
        el("label", {}, "height ×", exag), colors, el("label", {}, water, "sea level"),
        setting("voxel", "voxel m", "The voxel size the table's octaves round to"), setting("lods", "LODs", "The LOD count: the octaves the ground has"));
}

// --- the selected biome's controls ---

function fmt_m(p_m) {
    if (p_m >= 1000) return `${+(p_m / 1000).toPrecision(3)} km`;
    return `${+p_m.toPrecision(3)} m`;
}

function amp_label(p_a) {
    const span = p_a.wavelength_m !== undefined ? fmt_m(p_a.wavelength_m)
        : p_a.to_m >= 1e6 ? `≥ ${fmt_m(p_a.from_m)}` : `${fmt_m(p_a.from_m)}–${fmt_m(p_a.to_m)}`;
    return p_a.field === "ground" ? span : `${p_a.field} ${span}`;
}

// A number on a slider and in a box; p_set(value) writes it into the table (undefined: the key is removed).
function knob(p_label, p_value, p_max, p_step, p_set, p_title = "") {
    const range = el("input", { type: "range", min: 0, max: p_max, step: p_step, value: p_value ?? 0 });
    const box = el("input", { type: "number", step: p_step, value: p_value ?? "" });
    range.addEventListener("input", () => { box.value = range.value; edit(() => p_set(Number(range.value)), false); });
    range.addEventListener("change", end_gesture);
    box.addEventListener("change", () => {
        const v = box.value.trim() === "" ? undefined : Number(box.value);
        if (v !== undefined) range.value = v;
        edit(() => p_set(v));
    });
    return el("div", { class: "knob", title: p_title }, el("label", { title: p_label }, p_label), range, box);
}

function set_key(p_obj, p_key, p_v) {
    if (p_v === undefined || p_v === "") delete p_obj[p_key];
    else p_obj[p_key] = p_v;
}

function color_swatch(p_label, p_obj, p_key, p_fallback, p_after) {
    const i = el("input", { type: "color", value: p_obj?.[p_key] || p_fallback });
    i.addEventListener("input", () => edit(() => { p_after(i.value); }, false));
    i.addEventListener("change", () => { end_gesture(); render_biomes(); });
    return el("label", {}, i, p_label);
}

function render_controls() {
    const box = $("#controls");
    box.innerHTML = "";
    const b = current();
    if (!b) { box.append(el("p", { class: "help" }, "This table has no biome. Add one in the full editor.")); return; }
    box.append(el("h2", {}, chip(b.debug_color), b.name),
        el("p", { class: "help" }, b.region ? `In region ${b.region}.` : "In no region.", " ",
            b.where ? "Grows where its edges below hold." : "The default of its region: grows where no other biome of it does."));
    render_shape(box, b);
    render_terrace(box, b);
    render_colours(box, b);
    render_relief(box, b);
    render_where(box, b);
}

// The biome's multipliers on the ground's octaves (its "amp" list): the landscape's spectrum, coarse to fine.
function render_shape(p_box, p_b) {
    p_box.append(el("h3", {}, "Shape"), el("p", { class: "help" },
        "How much of each size of relief this biome keeps (×1: the ground's own; 0: flat at that size)."));
    const amps = (p_b.amp || []).map((a, i) => [a, i]);
    const size = (a) => a.wavelength_m ?? a.to_m ?? 0;
    amps.sort((x, y) => size(y[0]) - size(x[0]));
    if (!amps.length) p_box.append(el("p", { class: "help" }, "No multiplier: the ground's own relief everywhere (add some in the full editor)."));
    for (const [a] of amps) {
        const k = knob(amp_label(a), a.x ?? 1, Math.max(4, Math.ceil((a.x ?? 1) * 2)), 0.01, (v) => set_key(a, "x", v),
            "×: this band's multiplier (default 1)");
        const shape = el("select", { title: "The noise's shape in this band" }, SHAPES.map((s) => el("option", { value: s, selected: (a.shape || "") === s }, s || "band's own")));
        shape.addEventListener("change", () => edit(() => set_key(a, "shape", shape.value)));
        const tags = [a.multifractal ? `multifractal ${a.multifractal}` : "", a.warp_m ? `warp ${fmt_m(a.warp_m)}` : ""].filter(Boolean).join(" · ");
        k.append(el("div", { class: "extra" }, shape, tags));
        p_box.append(k);
    }
}

function render_terrace(p_box, p_b) {
    const on = el("input", { type: "checkbox", checked: !!p_b.terrace });
    on.addEventListener("change", () => { edit(() => { if (on.checked) p_b.terrace = { step_m: 40 }; else delete p_b.terrace; }); render_controls(); });
    p_box.append(el("h3", {}, el("label", { class: "check" }, on, "Terraces")));
    if (!p_b.terrace) return;
    p_box.append(knob("step m", p_b.terrace.step_m, Math.max(200, p_b.terrace.step_m * 2), 1, (v) => set_key(p_b.terrace, "step_m", v)));
    const inv = el("input", { type: "checkbox", checked: !!p_b.terrace.invert });
    inv.addEventListener("change", () => edit(() => set_key(p_b.terrace, "invert", inv.checked || undefined)));
    p_box.append(el("label", { class: "check" }, inv, "inverted"));
}

function render_colours(p_box, p_b) {
    const surface = (v, k) => { p_b.surface ||= {}; p_b.surface[k] = v; paint(); };
    p_box.append(el("h3", {}, "Colours"), el("div", { class: "swatches" },
        color_swatch("flat", p_b.surface, "flat", "#6a8a3c", (v) => surface(v, "flat")),
        color_swatch("steep", p_b.surface, "steep", p_b.surface?.flat || "#7a7468", (v) => surface(v, "steep")),
        color_swatch("map", p_b, "debug_color", "#888888", (v) => { p_b.debug_color = v; paint(); })));
    if (!p_b.surface) p_box.append(el("p", { class: "help" }, "No surface: the procedural ground's colours. Picking one adds it."));
}

// The heights its landscape stands on (shared by its region's biomes).
function render_relief(p_box, p_b) {
    const region = S.mode === "solo" ? relief_of(p_b) : region_key(p_b);
    p_box.append(el("h3", {}, "Relief"));
    if (S.mode === "solo") {
        const pick = el("select", { title: "Whose heights the biome stands on, shown alone" },
            el("option", { value: "", selected: region === "" }, "(none: no region's heights)"),
            (S.data.regions || []).map((r) => el("option", { value: r.name, selected: r.name === region }, `region ${r.name}`)));
        pick.addEventListener("change", () => { S.relief[p_b.name] = pick.value; store_prefs(); render_controls(); run(QUICK_SIZE); });
        p_box.append(el("div", { class: "knob" }, el("label", {}, "stands on"), pick));
    }
    const heights = (S.data.heights || []).filter((h) => (h.region ?? "") === region);
    const sharing = biomes().filter((x) => region_key(x) === region).map((x) => x.name);
    p_box.append(el("p", { class: "help" }, heights.length
        ? `The ground's heights${region ? ` of region ${region}` : " of no region"}, shared by ${sharing.join(", ")}. Curves in the full editor.`
        : "No height of this region: the ground's own noise only."));
    for (const h of heights) {
        p_box.append(knob(`${h.field}${h.curve ? " (curve)" : ""}`, h.height_m, Math.max(1000, Math.ceil(h.height_m * 2)), 1, (v) => set_key(h, "height_m", v),
            "height_m: metres at the curve's (or the field's) 1"));
    }
}

// Where it grows among its neighbours: the edges of its "where".
function render_where(p_box, p_b) {
    if (S.mode === "solo" || !p_b.where) return;
    p_box.append(el("h3", {}, "Where it grows"), el("p", { class: "help" }, "Between min and max of each field, fading over fade."),
        el("div", { class: "edge head" }, el("span", {}, "field"), el("span", {}, "min"), el("span", {}, "max"), el("span", {}, "fade")));
    for (const e of p_b.where) {
        const num = (k) => {
            const i = el("input", { type: "number", step: 0.01, value: e[k] ?? "" });
            i.addEventListener("change", () => edit(() => set_key(e, k, i.value.trim() === "" ? undefined : Number(i.value))));
            return i;
        };
        p_box.append(el("div", { class: "edge" }, el("span", {}, e.field), num("min"), num("max"), num(e.fade_min !== undefined ? "fade_min" : "fade")));
    }
}

// --- the view's pointer: a click names the point, a double click moves the slice there ---

function wire_pointer(p_canvas) {
    let down = null;
    p_canvas.addEventListener("pointerdown", (e) => { down = [e.clientX, e.clientY]; });
    p_canvas.addEventListener("pointerup", (e) => {
        if (!down || Math.hypot(e.clientX - down[0], e.clientY - down[1]) > 4 || !S.run) return;
        const p = view.pick(e);
        if (!p) return;
        const R = S.run, k = p.j * R.meta.n + p.i;
        S.probe = [Math.round(R.meta.center_m[0] + p.x), Math.round(R.meta.center_m[1] + p.z)];
        const probe = $("#probe");
        probe.hidden = false;
        probe.textContent = `${R.meta.biomes[R.picks[k]] ?? "?"} · ${Math.round(R.h[k])} m · at ${S.probe.join(",")} (Fly it starts here)`;
    });
    p_canvas.addEventListener("dblclick", (e) => {
        const p = view.pick(e);
        if (!p || !S.run) return;
        S.center = [Math.round(S.run.meta.center_m[0] + p.x), Math.round(S.run.meta.center_m[1] + p.z)];
        store_prefs();
        render_viewbar();
        run(QUICK_SIZE);
    });
}

async function fly() {
    const spawn = S.probe || S.center;
    const args = ["--preset=video", `--spawn=${spawn.join(",")}`, "--altitude=300", `--lods=${S.lods}`, `--voxel=${S.voxel}`];
    if (S.colors === "debug") args.push("--view=12");
    try {
        const r = await api("/api/launch", { path: S.path, data: view_table(), engine_args: "--render-thread safe", game_args: args.join(" ") });
        toast(`viewer launched (log ${r.log})`);
    } catch (e) { toast(e.message, true); }
}

// --- wiring ---

async function main() {
    load_prefs();
    view = new View3D($("#view"));
    view.set_exaggeration(S.exaggeration);
    view.show_water(S.water);
    wire_pointer($("#view"));
    $("#table").addEventListener("change", (e) => open_table(e.target.value).catch((x) => toast(x.message, true)));
    $("#save").addEventListener("click", save);
    $("#undo").addEventListener("click", () => undo(S.undo, S.redo));
    $("#redo").addEventListener("click", () => undo(S.redo, S.undo));
    $("#fly").addEventListener("click", fly);
    $("#open-editor").addEventListener("click", () => go_to("editor.html", S.path, S.data, S.saved));
    document.addEventListener("keydown", (e) => {
        const mod = e.ctrlKey || e.metaKey;
        if (mod && e.key === "s") { e.preventDefault(); save(); }
        const typing = ["INPUT", "TEXTAREA", "SELECT"].includes(document.activeElement?.tagName) && document.activeElement.type !== "range";
        if (mod && !typing && e.key.toLowerCase() === "z") { e.preventDefault(); e.shiftKey ? undo(S.redo, S.undo) : undo(S.undo, S.redo); }
    });
    window.addEventListener("beforeunload", (e) => { if (dirty() && !handed_off()) e.preventDefault(); });
    const r = await api("/api/tables");
    S.tables = r.tables;
    const sel = $("#table");
    for (const t of r.tables) sel.append(el("option", { value: t.path }, t.path + (t.generated ? "  (generated by world.py)" : "")));
    const handoff = take_handoff();
    if (handoff) return set_table(handoff.path, handoff.data, handoff.saved);
    const want = r.tables.some((t) => t.path === S.path) ? S.path : r.tables.find((t) => t.path === "world.json")?.path || r.tables[0]?.path;
    if (want) await open_table(want);
}

main().catch((e) => toast(e.message, true));
